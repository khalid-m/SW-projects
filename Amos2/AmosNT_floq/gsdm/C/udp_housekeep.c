////////////////////////////////////////////////////////////////////////////
//
// Handles and dispatches a command from a client.
//
// Returns:
//
//   On success:  1      (command valid & handled)
//                0      (command valid, but ignored)
//
//   On error:    nil    (invalid command)
oidtype udp_housekeep_handle_commandfn( bindtype env,
					oidtype host,
					oidtype port,
					oidtype data,
					oidtype datasize )
{
  udp_hk_client_t *client = NULL;
  udp_hk_packet_t *hkp;
  char *pHost = NULL;
  int iPort, iDatasize, res = -1;

  DBG(("%s()\n", __FUNCTION__));
  if (udp_housekeep_status==PSTATUS_OFF) {
    DBG(("%s: udp housekeeping service is not started!\n", __FUNCTION__));
    return nil;
  }

  // Check arguments
  IntoString(host, pHost, env);
  IntoInteger(port, iPort, env);
  OfType(data, BINARYTYPE, env);
  IntoInteger( datasize, iDatasize, env );

  hkp = (udp_hk_packet_t *)&(dr(data,binarycell)->cont);
  if (!hkp) return lerror( ILLEGAL_ARGUMENT, data, env );


  // Determine what kind of command this is.
  
  // Identify 
  // If duplicate ID messagess are received, we respond 
  // to each message anyway with the client's ID.
  if (hkp->type[0]=='I' && hkp->type[1]=='D') {
    res = udp_housekeep_client_ID( pHost, iPort );  
    return mkinteger(res);
  } 

  // If this client has identified itself with us, we have its
  // descriptor in our table.  Find descriptor by client's ip:port
  client = udp_housekeep_find_client( pHost, iPort );

  // At this point, if we don't have a client descriptor, then we
  // ignore the command packet.  Clients must always ident themselves.
  if (client==NULL)
    return nil;

  // Ok, client had identified itself before.

  // Client options
  if (hkp->type[0]=='C') {
    if (hkp->type[1]=='O') {
      // 'CO' == client options
      // res = udp_housekeep_client_CO( client );
    }
  }

  if (hkp->type[0]=='A') {
    if (hkp->type[1]=='C') {
      // 'AC' == acknowledge 
      // res = udp_housekeep_client_CO( client,  );
    }
  }

  

  return (res==-1) ? nil : mkinteger(res);
}



////////////////////////////////////////////////////////////////////////////
// 
// Sends udp radio packet to all connected clients (i.e. clients that
// have identified themselves & requested that streaming starts).
// Current implementation uses high-level udp-streams functions, which
// is relatively slow.
//
// TODO: The obvious optimization is to obtain a (struct sockaddr*)
// for each vis-client at connection & identification time, and then
// use the low-level internal function udp_stream_senddata_to()
// directly.  That way we wouldn't need to manually "redirect" the udp
// stream and only need to resolve the vis-client address once.
//
oidtype udp_housekeep_send_packetfn( bindtype env,
				     oidtype data,
				     oidtype datasize)
{
  udp_hk_client_t *client;
  int iDatasize, i=0;
  char *pData;

  //  DBG(("%s()\n", __FUNCTION__));
  if (udp_housekeep_status==PSTATUS_OFF) {
    DBG(("%s: udp housekeep is not started!\n", __FUNCTION__));
    return nil;
  }

  OfType(data, BINARYTYPE, env);
  IntoInteger( datasize, iDatasize, env );

  // get pointer to data
  pData = (char *)&(dr(data,binarycell)->cont);
  if (!pData) return lerror( ILLEGAL_ARGUMENT, data, env );

  // Dispatch to every client using the same UDP stream
  client = udp_hk_clients_first_elem();

  while( i<udp_hk_clients_num_elements && client != NULL ) {

    int res = 0;
    if ( client->status == CSTATUS_RECEIVING ) {
      if (udp_stream_redirect( udp_housekeep_stream_id, client->hostname, client->port )) {
	if (udp_stream_put( udp_housekeep_stream_id, pData, iDatasize ))
	  res = 1;
      }
    }

    client = udp_hk_clients_next_elem( client );
    i++;
  }

  return nil;
}

