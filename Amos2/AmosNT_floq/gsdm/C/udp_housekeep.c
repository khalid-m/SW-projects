////////////////////////////////////////////////////////////////////////////
// Get ready to produce housekeeping packets (opens new UDP stream)
//
// Returns: 
//
//   On success:  id number of the housekeep's udp-stream 
//   On failure:  nil
//
oidtype udp_housekeep_startfn(bindtype env)
{
  DBG(("%s()\n", __FUNCTION__));

  if (udp_housekeep_status == PSTATUS_ON) {
    ERR(("%s(): Housekeep already started\n", __FUNCTION__));
    return nil;
  }

  // Create a read/write udp stream listening on port MYPORT
  udp_housekeep_stream_id = udp_stream_open( MYPORT, "", 0, 1, 1 );

  if (udp_housekeep_stream_id != -1) {
    udp_housekeep_status = PSTATUS_ON;
    return mkinteger(udp_housekeep_stream_id);
  } 

  // errors
  return nil;
}
