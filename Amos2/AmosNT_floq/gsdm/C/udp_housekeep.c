#define PSTATUS_OFF 0
#define PSTATUS_ON  1

// Client status values
#define CSTATUS_STOPPED 0
#define CSTATUS_RECEIVING 1


////////////////////////////////////////////////////////////////////////////
//
// visualization client descriptor
//
struct udp_hk_client {
  struct udp_hk_client *prev;
  struct udp_hk_client *next;
  int id;                  // id (auto generated by the hashtable functions)

  int key;                 // hash key based on the hostname & port
  int status;              // running or paused?
  char hostname[32];
  int port;

  // This is filled in, but not used:
  struct sockaddr_in addr; // resolved host address of the vis-client

  // Client-requested options
  // Flags
  unsigned int si_autosend  : 1;    // 1 = always send serverinfo packets automatically (at si_rate)
  unsigned int ts_autosend  : 1;    // 1 = always send timestamp packets automatically (at ts_rate)
  unsigned int si_onchange  : 1;    // 1 = send serverinfo when radio settings (freq, bw) change
  unsigned int reserved     : 5;
  // Rates:  once for every 2^rate radio-packets
  unsigned long si_rate;            // serverinfo packets rate (autosend_si must be set)
  unsigned long ts_rate;            // timestamp packets rate (autosend_ts must be set)

  // Fail-safe packet delivery: important packets are queued and
  // re-sent until delivery has been confirmed or UDP_MAX_RETRIES
  // exceeded.  If the outgoing queue becomes full, client is
  // disconnected (flow control would be useful here)
  udp_hk_packet_t hkp_queue[UDP_HKP_QUEUE_SIZE]; // outgoing packets FIFO queue
  unsigned short qhead; // first element to send
  unsigned short qtail; // first free location where to store a new queued packet
};

typedef struct udp_hk_client udp_hk_client_t;


