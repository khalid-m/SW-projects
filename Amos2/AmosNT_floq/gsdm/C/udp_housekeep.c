////////////////////////////////////////////////////////////////////////////
// Stop streaming udp data, delete info about all connected vis-clients
//
// Returns: 
//
//   On success: Number of clients with unique hosts that have been
//                "served" during the session
//
//   On failure: nil
//
oidtype udp_housekeep_stopfn(bindtype env)
{
  udp_hk_client_t *client;
  int i=0;

  DBG(("%s()\n", __FUNCTION__));
  if (udp_housekeep_status == PSTATUS_OFF) {
    ERR(("%s(): Housekeep not running\n", __FUNCTION__));
    return nil;
  }

  // Remove clients
  client = udp_hk_clients_first_elem();
  while( i<udp_hk_clients_num_elements && client != NULL ) {
    udp_hk_client_t *next = udp_hk_clients_next_elem( client );

    // Send 'end session' packet

    udp_hk_clients_delete_elem( client );
    client = next;
    i++;
  }

  // Close down udp stream
  udp_stream_close( udp_housekeep_stream_id );
  udp_housekeep_stream_id = -1;
  udp_housekeep_status = PSTATUS_OFF;

  return mkinteger(i);
}
