////////////////////////////////////////////////////////////////////////////
// simple hash from ip:port to integer
inline int make_hk_client_key(char *hostname, int port)
{
  unsigned int k = (unsigned int)port * 7;
  while (*hostname)
    k += (unsigned int)128 * k + (unsigned int)((char)*(hostname++));
  return (int)k;
}



////////////////////////////////////////////////////////////////////////////
// brute-force "find", traverses entire table like a linked list
static udp_hk_client_t * udp_housekeep_find_client(char *hostname, int port)
{
  int key = make_hk_client_key(hostname, port);
  udp_hk_client_t *client = udp_hk_clients_first_elem();
  int i=0;
  while( i<udp_hk_clients_num_elements && client != NULL ) {
    if (key==client->key)
      return client;
    i++;
    client = udp_hk_clients_next_elem( client );
  }
  return NULL;
}



////////////////////////////////////////////////////////////////////////////
// Handle client ID command.
// Creates a new client descriptor.
//
static int udp_housekeep_client_ID( char *hostname, int port )
{
  udp_hk_client_t *client = udp_hk_clients_create_elem();

  if (client==NULL)
    return 0;

  if ( udp_housekeep_initaddr(hostname, port, 
			     (struct sockaddr_in *)&(client->addr)) == 0) {
    udp_hk_clients_delete_elem( client );
    DBG(("Warning! Client connect attempt canceled: can't resolve client's host\n"));
    return 0; // 0 - ignored
  }

  client->key = make_client_key(hostname, port);
  client->status = CSTATUS_STOPPED;
  strncpy(client->hostname, hostname, 32);
  client->port = port;

  DBG(("UDP Housekeep: client (%s:%u) identified itself\n", hostname, port));
  return 1; // 1 - handled
}



////////////////////////////////////////////////////////////////////////////
// Handle Client Options command
// This sets streaming options and enables/disables several streams at once.
//
static int udp_housekeep_client_CO( udp_hk_client_t *client, hkp_clientopt_t *opt )
{
  client->status = CSTATUS_RECEIVING;
  DBG(("UDP Housekeep: client (%s:%i) sets options\n", client->hostname, client->port));
  return 1; // 1 - handled
}



