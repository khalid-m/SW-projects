////////////////////////////////////////////////////////////////////////////
// Stop streaming udp data, delete info about all connected vis-clients
//
// Returns: 
//
//   On success: Number of clients with unique hosts that have been
//                "served" during the session
//
//   On failure: nil
//
oidtype udp_producer_stopfn(bindtype env)
{
  udp_client_t *client;
  int i=0;

  DBG(("%s()\n", __FUNCTION__));
  if (udp_producer_status == PSTATUS_OFF) {
    DBG(("Producer not started!\n"));
    return nil;
  }

  // Close down udp stream
  udp_stream_close( udp_producer_stream_id );
  udp_producer_stream_id = -1;
  udp_producer_status = PSTATUS_OFF;

  // Delete all client infos
  client = udp_clients_first_elem();
  while( i<udp_clients_num_elements && client != NULL ) {
    udp_client_t *next = udp_clients_next_elem( client );
    udp_clients_delete_elem( client );
    client = next;
    i++;
  }

  return mkinteger(i);
}
