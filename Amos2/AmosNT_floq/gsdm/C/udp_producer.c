////////////////////////////////////////////////////////////////////////////
// Get ready to produce radio streams
//
// Returns: 
//
//   On success:  id number of the producer's udp-stream 
//   On failure:  nil
//
oidtype udp_producer_startfn(bindtype env)
{
  DBG(("%s()\n", __FUNCTION__));

  if (udp_producer_status == PSTATUS_ON) {
    DBG(("Producer already started!\n"));
    return nil;
  }

  // Create a read/write udp stream listening on port MYPORT
  udp_producer_stream_id = udp_stream_open( MYPORT, "", 0, 1, 1 );

  if (udp_producer_stream_id != -1) {
    udp_producer_status = PSTATUS_ON;
    return mkinteger(udp_producer_stream_id);
  } 

  // errors
  return nil;
}
