////////////////////////////////////////////////////////////////////////////
//
// Resolves canonical hostname:port pair into a socket address struct.
// Used internally by producer to resolve the inet address of a newly
// connecting vis-client.
//
// Returns:
//   On success: 1
//   On failure: 0
//
static int udp_producer_initaddr(char *hostname, int port, struct sockaddr_in *target_addr)
{
  struct hostent *he = gethostbyname(hostname); // returns pointer to static data

  if (he != NULL) {
    target_addr->sin_family = AF_INET;
    target_addr->sin_port = htons(port);
    target_addr->sin_addr = *((struct in_addr *)he->h_addr);
    memset(&(target_addr->sin_zero), '\0', 8);  // zero the rest of the struct
    return 1; // 1-ok
  } else {
    return 0;
  }
}
