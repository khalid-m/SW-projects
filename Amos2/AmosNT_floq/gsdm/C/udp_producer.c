////////////////////////////////////////////////////////////////////////////
//
// Handles and dispatches a command from a vis-client.
//
// Returns:
//
//   On success:  1      (command valid & handled)
//                0      (command valid, but ignored)
//
//   On error:    nil    (invalid command)
oidtype udp_producer_handle_commandfn( bindtype env,
				       oidtype host,
				       oidtype port,
				       oidtype data,
				       oidtype datasize,
                                       oidtype rstreamid )
{
  udp_client_t *client = NULL;
  udp_cwpacket_t *cwp;
  char *pHost = NULL;
  int iPort, iDatasize, iRSID, res = -1;

  DBG(("%s()\n", __FUNCTION__));
  if (udp_producer_status==PSTATUS_OFF) {
    DBG(("%s: udp producer is not started!\n", __FUNCTION__));
    return nil;
  }

  // Check arguments
  IntoString(host, pHost, env);
  IntoInteger(port, iPort, env);
  OfType(data, BINARYTYPE, env);
  IntoInteger( datasize, iDatasize, env );
  IntoInteger( rstreamid, iRSID, env );

  cwp = (udp_cwpacket_t *)&(dr(data,binarycell)->cont);
  if (!cwp) return lerror( ILLEGAL_ARGUMENT, data, env );

  // If this client has already identified itself with us, we already have its
  // descriptor in our table.  Find descriptor by client's ip:port
  client = udp_producer_find_client( pHost, iPort );

  // Determine what kind of command this is.
  
  // Identify user?
  if (cwp->type[0]=='I' && cwp->type[1]=='D') {

    // Only bother to add this new client if this is the first time it
    // tries to ident itself.
    if (client==NULL)
      res = udp_producer_client_ID( pHost, iPort );
    else
      res = 0;

    return mkinteger(res);
  } 

  // At this point, if we don't have a client descriptor, then we
  // ignore the command packet.  Clients must always ident themselves.
  if (client==NULL)
    return nil;

  // Ok, client had identified itself before.

  // Start or stop streaming?
  if (cwp->type[0]=='S') {
    if (cwp->type[1]=='A') {
      // 'SA' == start
      res = udp_producer_client_SA( client );
    } else if (cwp->type[1]=='C') {
      // 'SC' == stop
      res = udp_producer_client_SC( client );
    }
  }

  // Mixer-register setting?
  if (cwp->type[0]=='M') {
    if (cwp->type[1]=='S') {

      // res = udp_producer_client_MS( client, &(cwp->cw) );

      // Quick fix to allow *ALL* clients to configure radio
      // settings.
      // TODO: user hierarchy, low rank user can't change higher rank
      // user's settings

      udp_stream_put( iRSID, (char *) cwp, sizeof(udp_cwpacket_t) );
      res = 1;
      // end of quick and dirty fix
    }
  }

  return (res==-1) ? nil : mkinteger(res);
}



////////////////////////////////////////////////////////////////////////////
// 
// Sends udp radio packet to all connected (i.e. clients that have
// identified themselves & requested that streaming starts)
// visualization clients.  Current implementation uses high-level
// udp-streams functions, which is relatively slow.
//
// TODO: The obvious optimization is to obtain a (struct sockaddr*)
// for each vis-client at connection & identification time, and then
// use the low-level internal function udp_stream_senddata_to()
// directly.  That way we wouldn't need to manually "redirect" the udp
// stream and only need to resolve the vis-client address once.
//
oidtype udp_producer_send_packetfn( bindtype env,
				    oidtype data,
				    oidtype datasize)
{
  udp_client_t *client;
  int iDatasize, i=0;
  char *pData;

  //  DBG(("%s()\n", __FUNCTION__));
  if (udp_producer_status==PSTATUS_OFF) {
    DBG(("%s: udp producer is not started!\n", __FUNCTION__));
    return nil;
  }

  OfType(data, BINARYTYPE, env);
  IntoInteger( datasize, iDatasize, env );

  // get pointer to data
  pData = (char *)&(dr(data,binarycell)->cont);
  if (!pData) return lerror( ILLEGAL_ARGUMENT, data, env );

  // Dispatch to every client using the same UDP stream
  client = udp_clients_first_elem();

  while( i<udp_clients_num_elements && client != NULL ) {

    int res = 0;
    if ( client->status == CSTATUS_RECEIVING ) {
      if (udp_stream_redirect( udp_producer_stream_id, client->hostname, client->port )) {
	if (udp_stream_put( udp_producer_stream_id, pData, iDatasize ))
	  res = 1;
      }
    }

    client = udp_clients_next_elem( client );
    i++;
  }

  return nil;
}

