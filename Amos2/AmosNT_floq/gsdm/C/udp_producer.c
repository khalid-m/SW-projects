// Port on which to listen for connections
#define MYPORT 4096

// Producer status values
#define PSTATUS_OFF 0
#define PSTATUS_ON  1

// Client status values
#define CSTATUS_STOPPED 0
#define CSTATUS_RECEIVING 1


////////////////////////////////////////////////////////////////////////////
//
// visualization client descriptor
//
struct udp_client {
  struct udp_client *prev;
  struct udp_client *next;
  int id;                  // id (auto generated by the hashtable functions)

  int key;                 // hash key based on the hostname & port
  int status;              // running or paused?
  char hostname[32];
  int port;

// This is filled in, but not used:
  struct sockaddr_in addr; // resolved host address of the vis-client

// These are not even filled in:
  // parameters that the client has requested so far, decoded from CWs
  float freq;
  float red;               // defines signal bandwidth, BW = fs/(4*2^red)
  float gain;
};

typedef struct udp_client udp_client_t;


