    public void loadGrammar(String filename, String grammar) {
        try {
            ap.grammar = grammar;

            // 1. Load grammar
            Tuple tpl = new Tuple(2);
            tpl.setElem(0, filename);
            tpl.setElem(1, grammar);
            ap.conn.callFunction(ap.loadFn, tpl);

            Tuple symbolTpl = new Tuple(1);
            symbolTpl.setElem(0, grammar);
            Scan scan;
            Tuple res;

            // 2. Populate rule table
            rulesModel.setRowCount(0);
            int ruleCnt = 0;            
            scan = ap.conn.callFunction(ap.getRulesFn, symbolTpl);
            while (!scan.eos()) {
                res = scan.getRow();
                ruleCnt++;
                Object[] row = new Object[4];
                row[0] = new Integer(ruleCnt);
                Tuple lpSeq = new Tuple(1); //Initialize second column with singleton tuples
                lpSeq.setElem(0, res.getStringElem(0)); //to use the same HTML renderer
                row[1] = lpSeq;
                row[2] = res.getSeqElem(1);
                row[3] = res.getStringElem(2);
                rulesModel.addRow(row);
                scan.nextRow();
            }

            //3. Populate terminals list
            tsModel.clear();
            scan = ap.conn.callFunction(ap.getTsFn, symbolTpl);
            while (!scan.eos()) {
                res = scan.getRow();
                tsModel.addElement(res.getStringElem(0));
                scan.nextRow();
            }

            //4. Populate nonterminals list
            ntsModel.clear();
            scan = ap.conn.callFunction(ap.getNTsFn, symbolTpl);
            while (!scan.eos()) {
                res = scan.getRow();
                ntsModel.addElement(res.getStringElem(0));
                scan.nextRow();
            }
        } catch (AmosException e) { JOptionPane.showMessageDialog(null, e); }
    }

