    private void jMenuItem1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem1ActionPerformed
        JFileChooser fc = new JFileChooser();
        fc.addChoosableFileFilter(new FileNameExtensionFilter("Lisp Files (*.lsp)","lsp"));
        fc.setCurrentDirectory(new File("."));
        if (fc.showOpenDialog(this.getComponent())==JFileChooser.APPROVE_OPTION) {
            final String filename = fc.getSelectedFile().toString();
            selectGrammarForm = new SelectGrammarForm(ap,filename);
            selectGrammarForm.selectButton.addActionListener(new ActionListener() {
                public void actionPerformed(ActionEvent e) {
                    selectGrammarForm.setVisible(false);
                    loadGrammar(filename,((SymbolEntries)selectGrammarForm.symbolList.getSelectedValue()).s);
                }
            });
            if (selectGrammarForm.symbolModel.getSize()==0) JOptionPane.showMessageDialog(null, "No symbols are assigned in file!");
            else if (selectGrammarForm.symbolModel.getSize()==1) 
                    loadGrammar(filename,((SymbolEntries)selectGrammarForm.symbolModel.getElementAt(0)).s);
            else selectGrammarForm.setVisible(true);
        }
    }//GEN-LAST:event_jMenuItem1ActionPerformed

